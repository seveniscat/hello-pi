import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';
import { importPi, saveReport } from './common.mjs';

const { CodemodeSandbox } = await importPi('node_modules/@earendil-works/pi-codemode/dist/index.js');
const input = JSON.parse(await readFile(new URL('./fixtures/review-data.json', import.meta.url), 'utf8'));
const trace = [];
const tools = ['tasks', 'checks'].map(name => ({
  name: `read_${name}`, description: `Read the local teaching ${name} fixture`,
  execute: async () => {
    trace.push(`${name}:start`);
    await delay(name === 'tasks' ? 60 : 20);
    trace.push(`${name}:end`);
    return input[name];
  },
}));
const sandbox = new CodemodeSandbox({ timeoutMs: 3000, tools });
let hostEffects = 0;
const effectSandbox = new CodemodeSandbox({ timeoutMs: 3000, tools: [{
  name: 'increment_host_counter', description: 'A deliberately visible in-memory host side effect, not a real notification',
  execute: async () => ({ count: ++hostEffects }),
}] });
const code = `
const [tasks, checks] = await Promise.all([
  tools.read_tasks({}), tools.read_checks({}),
]);
const byTask = new Map(checks.map(check => [check.taskId, check]));
return tasks
  .filter(task => task.archived !== true && task.status !== 'done' && byTask.get(task.id)?.result === 'failed')
  .map(task => ({ id: task.id, reason: byTask.get(task.id).reason }));
`;
try {
  const result = await sandbox.execute(code);
  assert.equal(result.ok, true, JSON.stringify(result));
  assert.deepEqual(result.value, [{ id: 'T-101', reason: '缺省 archived 被遗漏' }]);
  assert.equal(trace.slice(0, 2).filter(x => x.endsWith(':start')).length, 2);
  assert.doesNotMatch(JSON.stringify(result.value), /ownerEmail|internalNote|fullLog/);
  const primaryTrace = [...trace];
  const hostAccess = await sandbox.execute('return process.cwd();');
  assert.equal(hostAccess.ok, false);
  const faultyFilter = await sandbox.execute(code.replace("task.status !== 'done' && ", ''));
  assert.equal(faultyFilter.ok, true);
  assert.ok(faultyFilter.value.some(task => task.id === 'T-103'));
  const partial = await effectSandbox.execute('await tools.increment_host_counter({}); throw new Error("after-side-effect");');
  assert.equal(partial.ok, false);
  assert.equal(hostEffects, 1);
  await saveReport('codemode', {
    mode: 'REAL_PI_CODEMODE_1_1_0_QUICKJS_WITH_LOCAL_TOOLS_NO_MODEL_NO_MCP',
    realComponents: ['CodemodeSandbox', 'QuickJS WASM worker', 'injected host-tool calls'],
    code, trace: primaryTrace, result: result.value,
    rawFixtureCharacters: JSON.stringify(input).length,
    returnedCharacters: JSON.stringify(result.value).length,
    missingDoneFilterResult: faultyFilter.value,
    directProcessAccess: { ok: hostAccess.ok, error: hostAccess.error },
    scriptFailureDoesNotRollBackHostCounter: { scriptOk: partial.ok, hostEffects },
    limits: ['Tools read local teaching data; no MCP connection or remote service was tested.', 'The script is authored, not generated by a model.', 'Character counts are not token, price, latency or quality benchmarks.', 'The host counter is an in-memory side-effect illustration, not an external notification test.'],
  });
} finally { await sandbox.close(); await effectSandbox.close(); }
